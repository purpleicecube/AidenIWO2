function addLog(dict: SharedDict, node: string, message: string, metadata?: any) {
  dict.logs.push({ node, message, metadata });
}

async function emitNodeLog(dict: SharedDict, node: string, message: string, metadata?: any) {
  addLog(dict, node, message, metadata);
  if (dict.workOrder.id) {
    await storage.createExecutionLog({
      workOrderId: dict.workOrder.id,
      tier: 2,
      action: `PocketFlow: ${node}`,
      message,
      metadata: { ...metadata, iteration: dict.iteration, node },
    });
  }
}

function getEffectiveSettings(dict: SharedDict): LlmSettings | null {
  if (dict.llmConfig) return effectiveConfigToSettings(dict.llmConfig);
  return dict.llmSettings;
}

function getEffectiveApiKey(dict: SharedDict): string | undefined {
  return dict.llmConfig?.directApiKey || (dict.llmConfig ? dict.llmConfig.apiKeyEnvVar : undefined);
}

function getSystemPrompt(dict: SharedDict): string {
  const base = dict.llmConfig?.systemPrompt || dict.llmSettings?.systemPrompt || "";

  // Inject skill content from prompt_injection tools into system prompt
  const injectedSkills = (dict.availableTools || [])
    .filter(t => t.executionMode === "prompt_injection" && t.skillContent)
    .map(t => `\n\n---\n## Skill: ${t.name}\n${t.skillContent}`)
    .join("");

  if (!injectedSkills) return base;

  return base + "\n\n# LOADED SKILLS\nThe following skills have been loaded into your context. Use their instructions when the work order requires their capabilities." + injectedSkills;
}

async function nodeValidateWorkOrder(dict: SharedDict): Promise<NodeResult> {
  const order = dict.workOrder;

  if (!order.title || !order.description) {
    dict.blocked = true;
    dict.bdmMarker = {
      type: "validation_failure",
      reason: "Work order missing required fields (title or description)",
      tier: 2,
      timestamp: new Date().toISOString(),
    };
    await emitNodeLog(dict, "ValidateWorkOrder", `Validation failed: missing required fields`, { blocked: true });
    return { action: "bdm" };
  }

  if (!order.type || !order.priority) {
    dict.blocked = true;
    dict.bdmMarker = {
      type: "validation_failure",
      reason: "Work order missing type or priority classification",
      tier: 2,
      timestamp: new Date().toISOString(),
    };
    await emitNodeLog(dict, "ValidateWorkOrder", `Validation failed: missing type/priority`, { blocked: true });
    return { action: "bdm" };
  }

  const fallbackBlock = shouldBlockFallback(order);
  if (fallbackBlock.blocked) {
    dict.blocked = true;
    dict.bdmMarker = {
      type: "policy_block",
      reason: fallbackBlock.reason,
      tier: 2,
      timestamp: new Date().toISOString(),
    };
    await emitNodeLog(dict, "ValidateWorkOrder", `Blocked by policy rule: ${fallbackBlock.reason}`, { blocked: true });
    return { action: "bdm" };
  }

  await emitNodeLog(dict, "ValidateWorkOrder", `Schema validated for "${order.title}" (${order.type}/${order.priority})`, {
    valid: true,
    title: order.title,
    type: order.type,
    priority: order.priority,
  });

  return { action: "continue" };
}

/**
 * Loop 13 WI-2: Detect multi-page HTML/site requests and generate a structured
 * decomposition plan instead of falling back to a single "Execute Work Order" step.
 * Returns null if the request is not a multi-page HTML build.
 */
function buildMultiPageHtmlPlan(dict: SharedDict): PlanStep[] | null {
  const text = `${dict.workOrder.title} ${dict.workOrder.description || ""}`.toLowerCase();

  // Only trigger for clearly multi-page site/website requests
  const isMultiPage = /\b(five.?page|5.?page|multi.?page|static\s+website|mini.?site)\b/.test(text)
    || (/\b(website|site)\b/.test(text) && /\b(pages?|home|about|contact|services)\b/.test(text));

  if (!isMultiPage) return null;

  // Extract page names from description if mentioned
  const pageMatches = text.match(/\b(home|about|services?|products?|contact|portfolio|case.?stud|pricing|faq|blog|team)\b/g);
  const namedPages = pageMatches
    ? Array.from(new Set(pageMatches)).slice(0, 6)
    : ["home", "about", "services", "portfolio", "contact"];

  const steps: PlanStep[] = [
    {
      id: "step_design",
      name: "Define brand palette, typography, and design system",
      description: `Establish the CSS design system: colors, fonts, spacing, component styles. Follow any branding guidelines in the work order. Output a reusable CSS block.`,
      dependencies: [],
      status: "pending" as const,
    },
    {
      id: "step_nav",
      name: "Build site shell with navigation",
      description: `Create the shared HTML shell: header with navigation linking to all pages (${namedPages.join(", ")}), footer, and responsive layout structure. Output complete HTML with nav links.`,
      dependencies: ["step_design"],
      status: "pending" as const,
    },
    {
      id: "step_home",
      name: `Build page: ${namedPages[0] || "Home"}`,
      description: `Create the ${namedPages[0] || "Home"} page with hero section, value proposition, and key content. Use the design system and navigation shell from prior steps.`,
      dependencies: ["step_nav"],
      status: "pending" as const,
    },
    {
      id: "step_inner_pages",
      name: `Build remaining pages: ${namedPages.slice(1).join(", ")}`,
      description: `Create the remaining ${namedPages.length - 1} pages: ${namedPages.slice(1).join(", ")}. Each page must have unique content, use the shared navigation, and follow the design system. Output complete HTML for all pages.`,
      dependencies: ["step_nav"],
      status: "pending" as const,
    },
    {
      id: "step_polish",
      name: "Final assembly, linking, and polish",
      description: `Assemble all pages into a cohesive site. Ensure all navigation links work, add responsive design, accessibility attributes (ARIA labels, alt text), and any interactive elements. Output the final complete HTML.`,
      dependencies: ["step_home", "step_inner_pages"],
      status: "pending" as const,
    },
  ];

  return steps;
}

/**
 * Loop 13 WI-3: Detect likely incompleteness in multi-page HTML output.
 * Returns penalty info if the request asked for N pages but the output
 * appears to contain only one. Returns null if not applicable.
 */
function detectMultiPageIncompleteness(
  dict: SharedDict,
  output: string,
): { maxScore: number; gaps: string[] } | null {
  const text = `${dict.workOrder.title} ${dict.workOrder.description || ""}`.toLowerCase();

  // Only apply to multi-page requests
  const pageCountMatch = text.match(/\b(\d+).?page/);
  const requestedPages = pageCountMatch ? parseInt(pageCountMatch[1], 10) : 0;
  if (requestedPages < 2 && !/\b(multi.?page|static\s+website|mini.?site)\b/.test(text)) {
    return null;
  }
  const expectedPages = requestedPages || 5; // default assumption for "website"

  const outputLower = output.toLowerCase();
  const gaps: string[] = [];

  // Check 1: Count distinct page structures (look for page-level markers)
  const pageMarkers = (outputLower.match(/<\!--\s*page\b|<section\s+id=["'][^"']*page|<div\s+(?:id|class)=["'][^"']*page/g) || []).length;
  const h1Count = (output.match(/<h1[\s>]/g) || []).length;
  const navLinkCount = (outputLower.match(/<a\s+href=["']#?[^"']+["'][^>]*>/g) || []).length;

  // Check 2: Abrupt termination (no closing </html> or </body>)
  const hasClosingHtml = /<\/html\s*>/i.test(output);
  const hasClosingBody = /<\/body\s*>/i.test(output);
  const abruptlyTerminated = !hasClosingHtml && !hasClosingBody && output.length > 5000;

  // Check 3: Navigation links to other pages
  const hasNavigation = navLinkCount >= expectedPages - 1;

  // Build gap list
  if (h1Count < expectedPages && pageMarkers < expectedPages) {
    gaps.push(`Request asked for ${expectedPages} pages but output appears to contain ~${Math.max(h1Count, pageMarkers, 1)} page structure(s)`);
  }
  if (abruptlyTerminated) {
    gaps.push("Output appears truncated (no closing </html> or </body> tag)");
  }
  if (!hasNavigation && expectedPages > 1) {
    gaps.push(`Expected navigation to ${expectedPages} pages but found ${navLinkCount} navigation links`);
  }

  if (gaps.length === 0) return null;

  // Cap score at 0.55 — enough to trigger refinement, not enough to converge
  return { maxScore: 0.55, gaps };
}

async function nodePlanSteps(dict: SharedDict): Promise<NodeResult> {
  const settings = getEffectiveSettings(dict);
  const apiKey = getEffectiveApiKey(dict);
  const systemPrompt = getSystemPrompt(dict);

  const isRefinement = dict.iteration > 0;
  const existingGaps = dict.evaluationResult?.gaps || [];
  const existingOutputs = dict.accumulatedOutputs;

  if (!settings) {
    const singleStep: PlanStep = {
      id: "step_fallback",
      name: "Execute Work Order (Fallback)",
      description: `Process "${dict.workOrder.title}" using hardcoded policy engine`,
      dependencies: [],
      status: "pending",
    };
    dict.planSteps = [singleStep];
    dict.currentStepIndex = 0;
    await emitNodeLog(dict, "PlanSteps", `Fallback mode: single-step plan created (no LLM)`, { stepCount: 1, fallback: true });
    return { action: "continue" };
  }

  try {
    const planned = await llmPlanSteps(
      settings,
      systemPrompt,
      dict.workOrder,
      dict.tier1Result,
      isRefinement ? existingGaps : [],
      isRefinement ? existingOutputs : {},
      apiKey,
      dict.availableTools,
      dict.revisionContext,
      dict.designContext
    );

    if (isRefinement) {
      for (const newStep of planned) {
        const existing = dict.planSteps.find(s => s.id === newStep.id);
        if (!existing) {
          dict.planSteps.push({ ...newStep, status: "pending" });
        }
      }
      dict.currentStepIndex = dict.planSteps.findIndex(s => s.status === "pending");
      if (dict.currentStepIndex === -1) dict.currentStepIndex = 0;
    } else {
      const rawSteps = planned.map(s => ({ ...s, status: "pending" as const }));
      // Sanitize: remove dependency IDs that don't reference any step in this plan.
      // LLMs sometimes hallucinate dep IDs (wrong names, extra steps) causing deadlocks.
      const stepIds = new Set(rawSteps.map(s => s.id));
      dict.planSteps = rawSteps.map(s => ({
        ...s,
        dependencies: s.dependencies.filter(depId => stepIds.has(depId)),
      }));
      // Guard: if LLM returned an empty plan, try multi-page decomposition first,
      // then fall back to a single execution step.
      if (dict.planSteps.length === 0) {
        const multiPagePlan = buildMultiPageHtmlPlan(dict);
        if (multiPagePlan) {
          dict.planSteps = multiPagePlan;
          await emitNodeLog(dict, "PlanSteps", `LLM returned empty plan — injected structured multi-page HTML plan (${multiPagePlan.length} steps)`, {
            recovered: true, planType: "multi_page_html", stepCount: multiPagePlan.length,
            steps: multiPagePlan.map(s => ({ id: s.id, name: s.name, deps: s.dependencies })),
          });
        } else {
          dict.planSteps = [{
            id: "step_1",
            name: "Execute Work Order",
            description: `Produce the deliverable for "${dict.workOrder.title}" — ${dict.workOrder.description}`,
            dependencies: [],
            status: "pending" as const,
          }];
          await emitNodeLog(dict, "PlanSteps", `LLM returned empty plan — injecting single execution step`, { recovered: true, planType: "single_step" });
        }
      }
      dict.currentStepIndex = 0;
    }

    await emitNodeLog(dict, "PlanSteps",
      isRefinement
        ? `Delta refinement: ${planned.length} new/updated steps added (iteration ${dict.iteration})`
        : `Plan created: ${dict.planSteps.length} steps`,
      {
        stepCount: dict.planSteps.length,
        isRefinement,
        gaps: existingGaps,
        steps: dict.planSteps.map(s => ({ id: s.id, name: s.name, deps: s.dependencies })),
      }
    );

    return { action: "continue" };
  } catch (err: any) {
    // Loop 13 WI-2: Try multi-page decomposition before single-step fallback
    const multiPagePlan = buildMultiPageHtmlPlan(dict);
    if (multiPagePlan) {
      dict.planSteps = multiPagePlan;
      dict.currentStepIndex = 0;
      await emitNodeLog(dict, "PlanSteps", `LLM planning failed — injected structured multi-page HTML plan (${multiPagePlan.length} steps): ${err.message}`, {
        error: err.message, planType: "multi_page_html", stepCount: multiPagePlan.length,
      });
    } else {
      const singleStep: PlanStep = {
        id: "step_1",
        name: "Execute Work Order",
        description: `Process "${dict.workOrder.title}" — ${dict.workOrder.description}`,
        dependencies: [],
        status: "pending",
      };
      dict.planSteps = [singleStep];
      dict.currentStepIndex = 0;
      await emitNodeLog(dict, "PlanSteps", `LLM planning failed, using single-step fallback: ${err.message}`, { error: err.message, planType: "single_step" });
    }
    return { action: "continue" };
  }
}

function getReadySteps(dict: SharedDict): PlanStep[] {
  return dict.planSteps.filter(step => {
    if (step.status !== "pending") return false;
    return step.dependencies.every(depId => {
      const dep = dict.planSteps.find(s => s.id === depId);
      // If dep ID doesn't exist in the plan (hallucinated/stale), treat as satisfied.
      return !dep || dep.status === "completed";
    });
  });
}

function cascadeFailBlockedDeps(dict: SharedDict): PlanStep[] {
  const cascaded: PlanStep[] = [];
  let changed = true;
  while (changed) {
    changed = false;
    for (const step of dict.planSteps) {
      if (step.status !== "pending") continue;
      const hasFailedDep = step.dependencies.some(depId => {
        const dep = dict.planSteps.find(s => s.id === depId);
        return dep && (dep.status === "failed" || dep.status === "blocked");
      });
      if (hasFailedDep) {
        step.status = "failed";
        step.error = "Dependency failed — cascaded failure";
        cascaded.push(step);
        changed = true;
      }
    }
  }
  return cascaded;
}

async function nodeExecStep(dict: SharedDict): Promise<NodeResult> {
  const readySteps = getReadySteps(dict);

  if (readySteps.length === 0) {
    const hasBlocked = dict.planSteps.some(s => s.status === "blocked");
    if (hasBlocked) return { action: "bdm" };

    const allDone = dict.planSteps.every(s => s.status === "completed" || s.status === "failed");
    if (allDone) return { action: "done" };

    const cascaded = cascadeFailBlockedDeps(dict);
    if (cascaded.length > 0) {
      await emitNodeLog(dict, "ExecStep",
        `Cascade-failed ${cascaded.length} step(s) due to failed dependencies: ${cascaded.map(s => s.name).join(", ")}`,
        { cascadedSteps: cascaded.map(s => ({ id: s.id, name: s.name })) }
      );
      const allDoneNow = dict.planSteps.every(s => s.status === "completed" || s.status === "failed");
      if (allDoneNow) return { action: "done" };
      return { action: "more_steps" };
    }

    dict.blocked = true;
    dict.bdmMarker = {
      type: "execution_deadlock",
      reason: "No executable steps and not all steps complete — possible dependency deadlock",
      tier: 2,
      timestamp: new Date().toISOString(),
    };
    return { action: "bdm" };
  }

  const settings = getEffectiveSettings(dict);
  const apiKey = getEffectiveApiKey(dict);
  const systemPrompt = getSystemPrompt(dict);

  const executeStep = async (step: PlanStep): Promise<void> => {
    step.status = "running";

    await emitNodeLog(dict, "ExecStep", `Executing step "${step.name}"`, {
      stepId: step.id,
      stepName: step.name,
      parallel: readySteps.length > 1,
      availableTools: dict.availableTools.map(t => t.slug),
    });
    storage.createChecklistItem({
      workOrderId: dict.workOrder.id,
      phase: "tier2_exec",
      summary: `Step started: ${step.name}${dict.llmConfig ? ` (${dict.llmConfig.provider}/${dict.llmConfig.model})` : ""}${dict.availableTools.length > 0 ? ` — ${dict.availableTools.length} tools` : ""}`,
      addedBy: "system",
      status: "in_progress",
      iteration: dict.iteration,
    }).catch(() => {});

    try {
      if (!settings) {
        step.output = generateFallbackDeliverable(dict.workOrder);
      } else {
        // --- Observability: log step start with tool count, prompt size, provider/model ---
        const stepStartTime = Date.now();
        const toolCount = dict.availableTools.length;
        const promptSizeEstimate = (systemPrompt?.length || 0) + (dict.workOrder.description?.length || 0)
          + Object.values(dict.accumulatedOutputs).reduce((sum, o) => sum + o.length, 0);
        const llmProvider = dict.llmConfig?.provider || "unknown";
        const llmModel = dict.llmConfig?.model || "unknown";
        await emitNodeLog(dict, "ExecStep", `Step "${step.name}" LLM call starting — ${toolCount} tools, ~${Math.round(promptSizeEstimate / 4)} prompt tokens est, ${llmProvider}/${llmModel}`, {
          stepId: step.id,
          toolCount,
          promptSizeEstimate,
          llmProvider,
          llmModel,
          stepStartTime: new Date(stepStartTime).toISOString(),
        });

        // --- Forward-progress tracking: update heartbeat metadata so watchdog can distinguish ---
        if (dict.workOrder.id) {
          storage.updateWorkOrder(dict.workOrder.id, {
            heartbeatAt: new Date(),
          } as any).catch(() => {});
        }

        // --- Application-level timeout: 120s hard abort independent of SDK/provider timeout ---
        const STEP_TIMEOUT_MS = 120_000;
        // Phase 4: Prompt compaction — reduce prior outputs injected into prompt
        let stepOutputs = dict.accumulatedOutputs;
        if (dict.promptCompaction) {
          const entries = Object.entries(dict.accumulatedOutputs);
          const fullSize = entries.reduce((s, [, o]) => s + o.length, 0);

          if (entries.length > 0 && fullSize > 2000) {
            const hasDeps = step.dependencies && step.dependencies.length > 0;
            const depSet = hasDeps ? new Set(step.dependencies) : null;
            const filtered: Record<string, string> = {};

            if (depSet) {
              // Dependency-aware: full output for deps, truncated summary for others
              for (const [id, out] of entries) {
                if (depSet.has(id)) {
                  filtered[id] = out;
                } else {
                  filtered[id] = out.slice(0, 200) + (out.length > 200 ? `\n[...truncated, ${out.length} chars total]` : "");
                }
              }
            } else {
              // No declared deps: keep the most recent step's full output, truncate older ones
              const stepIds = entries.map(([id]) => id);
              const lastStepId = stepIds[stepIds.length - 1];
              for (const [id, out] of entries) {
                if (id === lastStepId) {
                  filtered[id] = out;
                } else {
                  filtered[id] = out.slice(0, 200) + (out.length > 200 ? `\n[...truncated, ${out.length} chars total]` : "");
                }
              }
            }

            const compactSize = Object.values(filtered).reduce((s, o) => s + o.length, 0);
            if (fullSize > compactSize) {
              console.log(`[perf:compact] Step "${step.name}" prompt compacted: ${Math.round(fullSize/4)}→${Math.round(compactSize/4)} tokens est (${Math.round((1 - compactSize/fullSize) * 100)}% reduction)`);
            }
            stepOutputs = filtered;
          }
        }

        const llmPromise = llmExecStep(
          settings,
          systemPrompt,
          dict.workOrder,
          step,
          stepOutputs,
          apiKey,
          dict.availableTools,
          dict.revisionContext,
          dict.designContext,
          dict.contextPack
        );
        const timeoutPromise = new Promise<never>((_, reject) =>
          setTimeout(() => reject(new Error(`llmExecStep timed out after ${STEP_TIMEOUT_MS / 1000}s — step "${step.name}" aborted. Provider: ${llmProvider}/${llmModel}, tools: ${toolCount}`)), STEP_TIMEOUT_MS)
        );
        const result = await Promise.race([llmPromise, timeoutPromise]);

        // --- Observability: log step completion ---
        const stepDurationMs = Date.now() - stepStartTime;
        await emitNodeLog(dict, "ExecStep", `Step "${step.name}" LLM call completed in ${(stepDurationMs / 1000).toFixed(1)}s — output: ${(result.output || "").length} chars`, {
          stepId: step.id,
          stepDurationMs,
          outputLength: (result.output || "").length,
          blocked: result.blocked,
        });

        if (result.blocked) {
          step.status = "blocked";
          step.error = result.reason || "Step blocked";
          dict.partialDeliverables.push(...Object.values(dict.accumulatedOutputs));
          dict.bdmMarker = {
            type: "step_block",
            reason: result.reason,
            stepId: step.id,
            stepName: step.name,
            tier: 2,
            timestamp: new Date().toISOString(),
          };
          await emitNodeLog(dict, "ExecStep", `Step "${step.name}" blocked: ${result.reason}`, {
            stepId: step.id,
            blocked: true,
          });
          return;
        }

        step.output = result.output || "";

        if (result.toolCalls && result.toolCalls.length > 0) {
          const useBatched = dict.batchedSynthesis && result.toolCalls.length > 1;

          if (useBatched) {
            // Phase 5: Batched tool synthesis — execute all tools, then one synthesis pass
            console.log(`[perf:batch] Step "${step.name}" batching ${result.toolCalls.length} tool calls`);
            const toolOutputSections: string[] = [];

            for (const tc of result.toolCalls) {
              await emitNodeLog(dict, "ToolCall", `Executing tool "${tc.toolSlug}" with input: ${tc.input.slice(0, 100)}`, {
                stepId: step.id, toolSlug: tc.toolSlug,
              });
              const agentId = dict.workOrder.assignedSubAgentId || "aiden-tier2";
              const toolResult = await executeTool(tc.toolSlug, tc.input, agentId, dict.workOrder.id);
              dict.toolResults.push(toolResult);

              if (toolResult.success) {
                await emitNodeLog(dict, "ToolCall", `Tool "${toolResult.toolName}" returned ${toolResult.output.length} chars in ${toolResult.durationMs}ms`, {
                  stepId: step.id, toolSlug: tc.toolSlug, leaseId: toolResult.leaseId, durationMs: toolResult.durationMs,
                });
                toolOutputSections.push(`### Tool Result: ${toolResult.toolName}\n${toolResult.output.slice(0, 3000)}`);
              } else {
                await emitNodeLog(dict, "ToolCall", `Tool "${toolResult.toolName}" failed: ${toolResult.error}`, {
                  stepId: step.id, toolSlug: tc.toolSlug, error: toolResult.error,
                });
                toolOutputSections.push(`### Tool "${toolResult.toolName}" — FAILED: ${toolResult.error}`);
              }
            }

            // One synthesis call with all tool results
            const allToolData = toolOutputSections.join("\n\n---\n");
            const combinedOutput = (step.output || "") + "\n\n---\n" + allToolData;

            if (settings && toolOutputSections.length > 0) {
              try {
                const synthesisResult = await llmExecStep(
                  settings,
                  systemPrompt,
                  dict.workOrder,
                  { ...step, description: `${step.description}\n\nThe following ${toolOutputSections.length} tool(s) returned data. Synthesize ALL results into your deliverable:\n\n${allToolData}` },
                  stepOutputs,
                  apiKey
                );
                if (!synthesisResult.blocked && synthesisResult.output) {
                  step.output = synthesisResult.output;
                  console.log(`[perf:batch] Batch synthesis succeeded — ${result.toolCalls.length} tools → 1 synthesis call (saved ${result.toolCalls.length - 1} LLM calls)`);
                } else {
                  step.output = combinedOutput;
                }
              } catch (synthErr: any) {
                await emitNodeLog(dict, "ToolCall", `Batch synthesis failed, keeping raw output: ${synthErr.message}`, { stepId: step.id });
                step.output = combinedOutput;
              }
            } else {
              step.output = combinedOutput;
            }

          } else {
            // Original N+1 pattern: one synthesis call per tool result
            for (const tc of result.toolCalls) {
              await emitNodeLog(dict, "ToolCall", `Executing tool "${tc.toolSlug}" with input: ${tc.input.slice(0, 100)}`, {
                stepId: step.id,
                toolSlug: tc.toolSlug,
              });

              const agentId = dict.workOrder.assignedSubAgentId || "aiden-tier2";
              const toolResult = await executeTool(tc.toolSlug, tc.input, agentId, dict.workOrder.id);
              dict.toolResults.push(toolResult);

              if (toolResult.success) {
                await emitNodeLog(dict, "ToolCall", `Tool "${toolResult.toolName}" returned ${toolResult.output.length} chars in ${toolResult.durationMs}ms`, {
                  stepId: step.id,
                  toolSlug: tc.toolSlug,
                  leaseId: toolResult.leaseId,
                  durationMs: toolResult.durationMs,
                });

                const toolOutputSection = `\n\n---\n### Tool Result: ${toolResult.toolName}\n${toolResult.output}`;
                const combinedOutput: string = (step.output || "") + toolOutputSection;

                if (settings) {
                  try {
                    const synthesisResult = await llmExecStep(
                      settings,
                      systemPrompt,
                      dict.workOrder,
                      { ...step, description: `${step.description}\n\nTool "${toolResult.toolName}" returned the following data. Synthesize it into your deliverable:\n${toolResult.output.slice(0, 3000)}` },
                      stepOutputs,
                      apiKey
                    );
                    if (!synthesisResult.blocked && synthesisResult.output) {
                      step.output = synthesisResult.output;
                    } else {
                      step.output = combinedOutput;
                    }
                  } catch (synthErr: any) {
                    await emitNodeLog(dict, "ToolCall", `Synthesis after tool call failed, keeping raw output: ${synthErr.message}`, { stepId: step.id });
                    step.output = combinedOutput;
                  }
                } else {
                  step.output = combinedOutput;
                }
              } else {
                await emitNodeLog(dict, "ToolCall", `Tool "${toolResult.toolName}" failed: ${toolResult.error}`, {
                  stepId: step.id,
                  toolSlug: tc.toolSlug,
                  error: toolResult.error,
                });
                step.output = (step.output || "") + `\n\n> Tool "${toolResult.toolName}" failed: ${toolResult.error}`;
              }
            }
          }
        }
      }

      step.status = "completed";
      dict.accumulatedOutputs[step.id] = step.output || "";
      dict.stepResults.push({
        stepId: step.id,
        stepName: step.name,
        output: step.output || "",
        iteration: dict.iteration,
      });

      await emitNodeLog(dict, "ExecStep", `Step "${step.name}" completed`, {
        stepId: step.id,
        outputLength: (step.output || "").length,
        toolsUsed: dict.toolResults.filter(r => r.success).map(r => r.toolSlug),
      });
      storage.createChecklistItem({
        workOrderId: dict.workOrder.id,
        phase: "tier2_exec",
        summary: `Step completed: ${step.name} (${((step.output || "").length / 1024).toFixed(1)}KB output${dict.toolResults.filter(r => r.success).length > 0 ? ", tools: " + dict.toolResults.filter(r => r.success).map(r => r.toolSlug).join(", ") : ""})`,
        addedBy: "system",
        status: "done",
        iteration: dict.iteration,
      }).catch(() => {});
    } catch (err: any) {
      step.status = "failed";
      step.error = err.message;
      await emitNodeLog(dict, "ExecStep", `Step "${step.name}" failed: ${err.message}`, {
        stepId: step.id,
        error: err.message,
      });
    }
  };

  if (readySteps.length > 1) {
    await emitNodeLog(dict, "ExecStep", `Parallel execution: ${readySteps.length} independent steps`, {
      steps: readySteps.map(s => s.name),
    });
    await Promise.all(readySteps.map(step => executeStep(step)));
  } else {
    await executeStep(readySteps[0]);
  }

  const hasBlocked = dict.planSteps.some(s => s.status === "blocked");
  if (hasBlocked) {
    dict.blocked = true;
    return { action: "bdm" };
  }

  const hasMorePending = dict.planSteps.some(s => s.status === "pending");
  if (hasMorePending) return { action: "more_steps" };

  return { action: "done" };
}

async function nodeEmitBDM(dict: SharedDict): Promise<NodeResult> {
  const partialOutput = Object.values(dict.accumulatedOutputs).join("\n\n---\n\n");
  dict.partialDeliverables = partialOutput ? [partialOutput] : [];

  await emitNodeLog(dict, "EmitBDM", `BDM marker emitted: ${dict.bdmMarker?.reason || "Unknown block"}`, {
    bdmMarker: dict.bdmMarker,
    partialOutputKeys: Object.keys(dict.accumulatedOutputs),
    iteration: dict.iteration,
  });

  return { action: "done" };
}

async function nodeEvaluate(dict: SharedDict, reviewReduction?: boolean): Promise<NodeResult> {
  const settings = getEffectiveSettings(dict);
  const apiKey = getEffectiveApiKey(dict);
  const systemPrompt = getSystemPrompt(dict);
  const combinedOutput = Object.values(dict.accumulatedOutputs).join("\n\n");

  const failedSteps = dict.planSteps.filter(s => s.status === "failed");
  if (failedSteps.length > 0 && dict.iteration < dict.maxIterations - 1) {
    const failedGaps = failedSteps.map(s => `Step "${s.name}" failed: ${s.error || "unknown error"}`);
    dict.evaluationScore = 0.4;
    dict.evaluationResult = {
      score: 0.4,
      meetsCriteria: false,
      gaps: failedGaps,
      strengths: dict.planSteps.filter(s => s.status === "completed").map(s => `Step "${s.name}" completed`),
      reasoning: `${failedSteps.length} step(s) failed — triggering refinement`,
    };
    await emitNodeLog(dict, "Evaluate", `${failedSteps.length} failed steps detected — forcing refinement`, {
      failedSteps: failedSteps.map(s => s.name),
      score: 0.4,
    });
    return { action: "refine" };
  }

  const completedSteps = dict.planSteps.filter(s => s.status === "completed");
  const allFailed = completedSteps.length === 0 && dict.planSteps.length > 0;

  if (allFailed) {
    dict.evaluationScore = 0.0;
    dict.evaluationResult = {
      score: 0.0,
      meetsCriteria: false,
      gaps: dict.planSteps.map(s => `Step "${s.name}" ${s.status}: ${s.error || "no output"}`),
      strengths: [],
      reasoning: "All steps failed — no deliverable produced",
    };
    await emitNodeLog(dict, "Evaluate", `All ${dict.planSteps.length} steps failed — best effort with empty output`, {
      score: 0.0,
      failedCount: dict.planSteps.length,
    });
    return { action: "best_effort" };
  }

  if (!settings || !combinedOutput) {
    dict.evaluationScore = 1.0;
    dict.evaluationResult = {
      score: 1.0,
      meetsCriteria: true,
      gaps: [],
      strengths: ["Execution completed"],
      reasoning: "Fallback mode — no evaluation needed",
    };
    await emitNodeLog(dict, "Evaluate", `Fallback mode: auto-converged (score=1.0)`, { score: 1.0 });
    return { action: "converged" };
  }

  // Phase 7: Review reduction — if first pass and all steps completed cleanly, auto-converge
  if (reviewReduction && dict.iteration === 0 && failedSteps.length === 0 && completedSteps.length === dict.planSteps.length) {
    dict.evaluationScore = 0.95;
    dict.evaluationResult = {
      score: 0.95,
      meetsCriteria: true,
      gaps: [],
      strengths: [`All ${completedSteps.length} steps completed on first pass`],
      reasoning: "Review reduction: first-pass clean completion — skipping LLM evaluation",
    };
    console.log(`[perf:review] Skipped LLM evaluation — first-pass clean (${completedSteps.length} steps, 0 failures)`);
    await emitNodeLog(dict, "Evaluate", `Review reduction: auto-converged on first pass (score=0.95)`, { score: 0.95, reviewReduction: true });
    return { action: "converged" };
  }

  try {
    const evalResult = await llmEvaluate(
      settings,
      systemPrompt,
      dict.workOrder,
      combinedOutput,
      dict.planSteps,
      apiKey,
      detectRequiredFormat(dict)
    );

    // Loop 13 WI-3: Completeness/truncation penalty for multi-page HTML.
    // If the request asked for multiple pages but output looks like a single page,
    // prevent the evaluator from over-scoring it as converged.
    const multiPagePenalty = detectMultiPageIncompleteness(dict, combinedOutput);
    if (multiPagePenalty) {
      const penalizedScore = Math.min(evalResult.score, multiPagePenalty.maxScore);
      if (penalizedScore < evalResult.score) {
        evalResult.score = penalizedScore;
        evalResult.meetsCriteria = false;
        evalResult.gaps = [...evalResult.gaps, ...multiPagePenalty.gaps];
        await emitNodeLog(dict, "Evaluate", `Multi-page completeness penalty applied: score capped to ${penalizedScore.toFixed(2)} (was ${dict.evaluationScore?.toFixed(2) || "?"})`, {
          penalty: multiPagePenalty, originalScore: dict.evaluationScore,
        });
      }
    }

    dict.evaluationScore = evalResult.score;
    dict.evaluationResult = evalResult;

    await emitNodeLog(dict, "Evaluate",
      `Quality score: ${evalResult.score.toFixed(2)} | Criteria met: ${evalResult.meetsCriteria} | Gaps: ${evalResult.gaps.length}`,
      { ...evalResult, iteration: dict.iteration }
    );

    if (evalResult.score >= dict.convergenceThreshold && evalResult.meetsCriteria) {
      storage.createChecklistItem({
        workOrderId: dict.workOrder.id,
        phase: "tier2_exec",
        summary: `Evaluation converged (score: ${evalResult.score.toFixed(2)}, iteration ${dict.iteration + 1})`,
        addedBy: "system",
        status: "done",
        iteration: dict.iteration,
      }).catch(() => {});
      return { action: "converged" };
    }

    storage.createChecklistItem({
      workOrderId: dict.workOrder.id,
      phase: "tier2_exec",
      summary: `Refinement triggered (score: ${evalResult.score.toFixed(2)}, gaps: ${evalResult.gaps.length})`,
      addedBy: "system",
      status: "done",
      iteration: dict.iteration,
    }).catch(() => {});

    if (dict.iteration >= dict.maxIterations - 1) {
      await emitNodeLog(dict, "Evaluate", `Max iterations (${dict.maxIterations}) reached — delivering best effort`, {
        score: evalResult.score,
      });
      return { action: "best_effort" };
    }

    return { action: "refine" };
  } catch (err: any) {
    dict.evaluationScore = 0.85;
    dict.evaluationResult = {
      score: 0.85,
      meetsCriteria: true,
      gaps: [],
      strengths: ["Execution completed"],
      reasoning: `Evaluation LLM failed (${err.message}), assuming acceptable quality`,
    };
    await emitNodeLog(dict, "Evaluate", `Evaluation LLM failed, auto-converging: ${err.message}`, { error: err.message });
    return { action: "converged" };
  }
}

async function nodeRefine(dict: SharedDict): Promise<NodeResult> {
  const settings = getEffectiveSettings(dict);
  const apiKey = getEffectiveApiKey(dict);
  const systemPrompt = getSystemPrompt(dict);
  const gaps = dict.evaluationResult?.gaps || [];

  if (!settings || gaps.length === 0) {
    await emitNodeLog(dict, "Refine", `No refinable gaps — converging`, { gaps: [] });
    return { action: "converged" };
  }

  try {
    const refinement = await llmRefine(
      settings,
      systemPrompt,
      dict.workOrder,
      gaps,
      dict.accumulatedOutputs,
      dict.planSteps,
      apiKey
    );

    dict.refinementHistory.push({
      iteration: dict.iteration,
      gaps: refinement.gaps,
      deltaSteps: refinement.deltaSteps.map(s => s.name),
    });

    for (const step of dict.planSteps) {
      if (step.status === "failed") {
        step.status = "pending";
        step.error = undefined;
      }
    }

    dict.iteration++;

    await emitNodeLog(dict, "Refine",
      `Refinement iteration ${dict.iteration}: ${refinement.deltaSteps.length} delta steps identified`,
      { gaps: refinement.gaps, deltaSteps: refinement.deltaSteps.map(s => s.name) }
    );

    return { action: "continue" };
  } catch (err: any) {
    await emitNodeLog(dict, "Refine", `Refinement LLM failed, converging with current output: ${err.message}`, { error: err.message });
    return { action: "converged" };
  }
}

function isIntermediateOutput(output: string): boolean {
  const trimmed = output.trim();
  if (trimmed.length < 20) return true;
  if (/^\s*[\[{]/.test(trimmed) && /[\]}]\s*$/.test(trimmed)) {
    try {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed) || (typeof parsed === "object" && parsed !== null)) {
        const str = JSON.stringify(parsed);
        if (!/<!DOCTYPE|<html|<body|<div|<section|<article/i.test(str)) {
          return true;
        }
      }
    } catch {}
  }
  const metadataPatterns = [
    /^\s*\{?\s*"(title|headlines|sections|layout|structure|wireframe|components)"\s*:/i,
    /^\s*(Step \d+ complete|Planning complete|Research complete|Data gathered)/i,
  ];
  if (metadataPatterns.some(p => p.test(trimmed))) return true;
  return false;
}

function selectBestHtmlOutput(outputs: Record<string, string>): string | null {
  let bestKey: string | null = null;
  let bestScore = -1;
  for (const [key, output] of Object.entries(outputs)) {
    if (!output || output.trim().length < 50) continue;
    let score = 0;
    if (/<!DOCTYPE\s+html/i.test(output)) score += 100;
    if (/<html[\s>]/i.test(output)) score += 80;
    if (/<head[\s>]/i.test(output) && /<body[\s>]/i.test(output)) score += 60;
    if (/<\/html>/i.test(output)) score += 40;
    if (/<meta\s/i.test(output)) score += 10;
    if (/<style[\s>]/i.test(output)) score += 10;
    if (score > bestScore) {
      bestScore = score;
      bestKey = key;
    }
  }
  return bestKey && bestScore >= 40 ? outputs[bestKey] : null;
}

function cleanDeliverable(raw: string): string {
  let cleaned = raw;
  if (/\\n/.test(cleaned) && !/<[a-z]/i.test(cleaned.substring(0, 200))) {
    cleaned = cleaned.replace(/\\n/g, "\n").replace(/\\t/g, "\t").replace(/\\"/g, '"');
  }
  cleaned = cleaned.replace(/^[\s\S]*?(<!DOCTYPE\s+html)/i, "$1");
  if (/<!DOCTYPE\s+html/i.test(cleaned) && /<\/html>/i.test(cleaned)) {
    const endIdx = cleaned.lastIndexOf("</html>") + "</html>".length;
    cleaned = cleaned.substring(0, endIdx);
  }
  return cleaned;
}

/**
 * Detect if the work order deliverable should be a specific file format
 * based on work order description and assigned tool skills.
 * If a gammaPolicy has already been resolved, its outputFormat takes precedence
 * over keyword/skill heuristics — the user explicitly chose a template.
 */
function detectRequiredFormat(dict: SharedDict): "pptx" | "pdf" | null {
  // Priority 0: Resolved gammaPolicy carries explicit format intent from the
  // user-selected template (e.g. klear_pdf_v1 → "pdf"). This MUST override
  // keyword/skill heuristics to prevent format-swap regressions (BUG-055).
  if (dict.gammaPolicy?.outputFormat === "pdf" || dict.gammaPolicy?.outputFormat === "pptx") {
    return dict.gammaPolicy.outputFormat;
  }

  const text = `${dict.workOrder.title} ${dict.workOrder.description}`.toLowerCase();

  // Explicit keyword matching takes priority over skill-based detection
  const hasPdfKeywords = /\b(pdf|portable\s*document)\b/.test(text);
  if (hasPdfKeywords) return "pdf";

  const hasPptxKeywords = /\b(pptx|powerpoint|slide\s*deck|presentation|pitch\s*deck|slides)\b/.test(text);
  if (hasPptxKeywords) return "pptx";

  // Fall back to skill-based detection
  const hasPptxSkill = dict.availableTools.some(
    t => t.executionMode === "prompt_injection" && /pptx|powerpoint|presentation/i.test(t.slug + " " + t.name)
  );
  if (hasPptxSkill) return "pptx";

  const hasPdfSkill = dict.availableTools.some(
    t => t.executionMode === "prompt_injection" && /pdf/i.test(t.slug + " " + t.name)
  );
  if (hasPdfSkill) return "pdf";

  return null;
}

